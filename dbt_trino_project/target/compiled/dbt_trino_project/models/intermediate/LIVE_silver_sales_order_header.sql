







with bronze_raw as (

    select
        salesorderid,
        revisionnumber,
        orderdate,
        duedate,
        shipdate,
        status,
        onlineorderflag,
        salesordernumber,
        purchaseordernumber,
        accountnumber,
        customerid,

        salespersonid,
        territoryid,
        billtoaddressid,
        shiptoaddressid,
        shipmethodid,
        creditcardid,
        creditcardapprovalcode,
        currencyrateid,

        subtotal,
        taxamt,
        freight,
        totaldue,

        comment,
        rowguid,
        modifieddate,

        -- metadata (tự thêm ở bronze)
        etl_date

    from "iceberg"."bronze"."bronze_sales_salesorderheader_LIVE"

    -- ✅ LUÔN chỉ xử lý đúng ngày dữ liệu được truyền vào
    where etl_date = date 'None'
),

calc_amounts as (
    select
        *,

        -- SUBTOTAL: clamp về [50, 1000]
        case
            when subtotal < 0      then 50
            when subtotal > 1000   then 1000
            else subtotal
        end as subtotal_clean,

        -- TAX: tính lại 10% của subtotal_clean
        round(
            case
                when subtotal is null then null
                else 0.10 * (
                    case
                        when subtotal < 0      then 50
                        when subtotal > 1000   then 1000
                        else subtotal
                    end
                )
            end,
            2
        ) as taxamt_clean,

        -- FREIGHT: đảm bảo không âm
        greatest(freight, 0) as freight_clean
    from bronze_raw
),

bronze_clean as (

    select
        salesorderid,
        revisionnumber,
        orderdate,
        duedate,
        shipdate,

        -- STATUS: 1–5 hợp lệ, ngoài range -> NULL
        case
            when status between 1 and 5 then status
            else null
        end as status,

        onlineorderflag,

        -- SALESORDERNUMBER: dữ liệu gốc thường SO + 5-6 chữ số
        case
            when regexp_like(salesordernumber, '^SO[0-9]{5,6}$')
                then salesordernumber
            else 'SO' || lpad(cast((salesorderid % 100000) as varchar), 5, '0')
        end as salesordernumber,

        -- PURCHASEORDERNUMBER: PO + digits (linh hoạt)
        case
            when purchaseordernumber is null then null
            when regexp_like(purchaseordernumber, '^PO[0-9]+$')
                then purchaseordernumber
            else 'PO' || cast(salesorderid as varchar)
        end as purchaseordernumber,

        -- ACCOUNTNUMBER: 10-40xx-###### (xx biến thiên)
        case
            when regexp_like(accountnumber, '^10-40[0-9]{2}-[0-9]{6}$')
                then accountnumber
            else '10-4030-' || lpad(cast(customerid as varchar), 6, '0')
        end as accountnumber,

        customerid,

        -- ID: ép về bigint
        cast(salespersonid  as bigint) as salespersonid,
        territoryid,
        billtoaddressid,
        shiptoaddressid,
        shipmethodid,
        cast(creditcardid   as bigint) as creditcardid,

        -- CREDITCARDAPPROVALCODE: digitsViDigits (linh hoạt)
        case
            when creditcardapprovalcode is null then null
            when regexp_like(creditcardapprovalcode, '^[0-9]+Vi[0-9]+$')
                then creditcardapprovalcode
            else
                lpad(cast(cast(creditcardid as bigint) as varchar), 5, '0')
                || 'Vi' ||
                lpad(cast((salesorderid % 100000) as varchar), 5, '0')
        end as creditcardapprovalcode,

        cast(currencyrateid as bigint) as currencyrateid,

        subtotal_clean as subtotal,
        taxamt_clean   as taxamt,
        freight_clean  as freight,

        round(
            coalesce(subtotal_clean, 0)
          + coalesce(taxamt_clean,   0)
          + coalesce(freight_clean,  0),
          2
        ) as totaldue,

        -- COMMENT: chuẩn hóa NULL, bỏ text fake
        case
            when comment is null then null
            when trim(comment) = '' then null
            when lower(trim(comment)) = 'fake order generated by faker' then null
            else comment
        end as comment,

        rowguid,
        modifieddate,

        -- ✅ giữ etl_date để trace batch ở silver (nếu không muốn thì xóa dòng này)
        etl_date

    from calc_amounts
)

select *
from bronze_clean